-- Debe coincidir con las entidades: Hibernate lo valida al arrancar (ddl-auto=validate).
-- Una migración YA aplicada no se edita nunca: los cambios van en una nueva (V3, V4…).

create table area (
    id      bigint generated by default as identity primary key,
    nombre  varchar(80) not null unique
);

create table categoria (
    id          bigint generated by default as identity primary key,
    nombre      varchar(60) not null unique,
    descripcion varchar(250),
    activa      boolean not null default true
);

create table usuario (
    id              bigint generated by default as identity primary key,
    nombre_completo varchar(120) not null,
    email           varchar(120) not null unique,
    password        varchar(100),
    rol             varchar(20) not null check (rol in ('SOLICITANTE', 'TECNICO', 'COORDINADOR')),
    activo          boolean not null default true,
    area_id         bigint references area (id)
);

-- Muchos a muchos: especialidades de cada técnico
create table usuario_categoria (
    usuario_id   bigint not null references usuario (id),
    categoria_id bigint not null references categoria (id),
    primary key (usuario_id, categoria_id)
);

create table ticket (
    id               bigint generated by default as identity primary key,
    asunto           varchar(120) not null,
    descripcion      varchar(2000) not null,
    prioridad        varchar(20) not null check (prioridad in ('BAJA', 'MEDIA', 'ALTA', 'CRITICA')),
    estado           varchar(20) not null check (estado in ('ABIERTO', 'EN_CURSO', 'RESUELTO', 'CERRADO', 'CANCELADO')),
    fecha_creacion   timestamp(6) not null,
    fecha_limite     timestamp(6) not null,
    fecha_resolucion timestamp(6),
    solicitante_id   bigint not null references usuario (id),
    tecnico_id       bigint references usuario (id),
    categoria_id     bigint not null references categoria (id),
    version          bigint
);

create table comentario (
    id        bigint generated by default as identity primary key,
    texto     varchar(2000) not null,
    fecha     timestamp(6) not null,
    interno   boolean not null default false,
    autor_id  bigint not null references usuario (id),
    ticket_id bigint not null references ticket (id)
);

-- Índices para las consultas más frecuentes
create index idx_ticket_estado on ticket (estado);
create index idx_ticket_solicitante on ticket (solicitante_id);
create index idx_comentario_ticket on comentario (ticket_id);